"""Sends assets from the Library into the mod's resources, with the right paths, and says exactly what changed.

Two steps, so nothing is written by surprise: plan() works out where each asset would go and what would happen (new file,
identical, would replace a different file, refused), then apply() writes only what the author confirmed. Folders the mod
generates (loot tables, codex) are refused: their generators are edited instead. Everything lands under the mod's own
namespace (assets/vestiges, data/vestiges), inside src/main/resources, and nothing is deleted.
"""
import json
import re
import time
from pathlib import Path

import explore
import export
import files
import libname
import licences
import pipeline
import projects

NAMESPACE = "vestiges"
RESOURCES = "src/main/resources"
LOG = "docs/assets/send-log.md"
# Folders the mod builds from tools; writing there by hand would be lost the next time the generator runs.
PROTECTED = (
    ("data/vestiges/loot_table/", "loot tables are generated by tools/build_loot.py: change that instead"),
    ("data/minecraft/loot_table/chests/", "chest loot is generated by tools/build_loot.py: change that instead"),
    ("data/vestiges/vestiges/codex/", "Codex entries are generated by tools/build_codex.py: change that instead"),
)
SAFE_PATH = re.compile(r"^(assets|data)/" + NAMESPACE + r"/[a-z0-9_./-]+\.[a-z0-9]+$")
# explore type -> the folder under data/vestiges/ for a file that has no path of its own
DATA_FOLDERS = {"loot": "loot_table", "recipe": "recipe", "advancement": "advancement", "tag": "tags", "worldgen": "worldgen", "function": "function"}


class SendProblem(Exception):
    pass


def mod_root(root):
    return Path(root) / RESOURCES


def _lower(name):
    return re.sub(r"[^a-z0-9_.-]+", "_", str(name).lower()).strip("._-")


def build_bytes(project):
    """(name, bytes, placement, problem) for a build's newest saved variant."""
    if not project.get("saved"):
        return None, None, None, "save a variant first (Save with proposed names)"
    chosen = project["saved"][-1]
    version = projects.load_version(project["id"], chosen["version"])
    errors = pipeline.inspect(version, lenient=True)["errors"]
    if errors:
        return chosen["name"], None, None, "the mod only uses vanilla blocks: " + "; ".join(errors[:2])
    structure, placement = export.to_structure(version, pipeline.jar().data_version(), with_air=project.get("mode") == "import")
    return chosen["name"], export.write_nbt(structure), placement, None


def default_destination(project):
    """Where an asset goes inside src/main/resources, from its original path when it has one, else from its kind."""
    if project.get("mode") != "file":
        game_id = libname.game_id(project)   # a numbered asset goes where its permanent game id says
        if game_id:
            namespace, path = game_id.split(":")
            return f"data/{namespace}/structure/{path}.nbt"
        return f"data/{NAMESPACE}/structure/{project.get('category', 'tree')}/{{name}}.nbt"
    file = project.get("file") or {}
    name = _lower(file.get("name", "file"))
    ftype = file.get("type", "")
    original = str(file.get("path", "")).replace("\\", "/")
    inner = re.match(r"^(?:[^/]+/)?(assets|data)/[^/]+/(.+)$", original)
    if inner:  # keep the original folders under the mod's namespace; the last part is the file's current name
        parts = [_lower(part) for part in inner.group(2).split("/")]
        parts[-1] = name
        return f"{inner.group(1)}/{NAMESPACE}/" + "/".join(parts)
    kind = project.get("category")
    if kind == "texture":
        return f"assets/{NAMESPACE}/textures/block/{name}"
    if kind == "sound":
        return f"assets/{NAMESPACE}/sounds/{name}"
    if kind == "model":
        return f"assets/{NAMESPACE}/models/block/{name}"
    return f"data/{NAMESPACE}/{DATA_FOLDERS.get(ftype, 'misc')}/{name}"


def check_destination(to):
    """None when the destination is fine, else the reason it is refused."""
    if ".." in to.split("/") or to.startswith("/") or "\\" in to:
        return "not a plain path inside the mod"
    if not SAFE_PATH.match(to):
        return f"must be under assets/{NAMESPACE}/ or data/{NAMESPACE}/, in lowercase letters, numbers, _ . - and /, with a file extension"
    for prefix, why in PROTECTED:
        if to.startswith(prefix):
            return why
    return None


def _compare(target, data):
    if not target.exists():
        return "new"
    return "same" if target.read_bytes() == data else "overwrite"


def plan(ids, root, edits=None):
    """One row per asset: where it goes and what would happen. edits maps an id to a destination typed by the author."""
    edits = edits or {}
    rows = []
    base = mod_root(root)
    for project_id in list(dict.fromkeys(str(i) for i in ids))[:2000]:
        try:
            project = projects.load(project_id)
        except KeyError:
            continue
        check = licences.of_project(project)
        row = {"id": project_id, "title": project.get("title", ""), "kind": project.get("category", ""), "licence": check["status"], "licence_words": check["words"],
               "needs_confirm": check["status"] in ("limited", "unknown"), "to": "", "action": "blocked", "note": "", "bytes": 0}
        if project.get("mode") == "file":
            data = projects.file_path(project_id)
            data = data.read_bytes() if data else None
            to = edits.get(project_id) or default_destination(project)
            problem = None if data is not None else "the file is missing"
        else:
            name, data, placement, problem = build_bytes(project)
            to = edits.get(project_id) or default_destination(project).replace("{name}", name or "build")
            row["placement"] = placement
        row["to"] = to
        problem = problem or check_destination(to)
        if problem:
            row["note"] = problem
        else:
            row["action"] = _compare(base / to, data)
            row["bytes"] = len(data)
            row["note"] = {"new": "will be created", "same": "already there and identical", "overwrite": "will replace a different file"}[row["action"]]
        rows.append(row)
    clashes = {}
    for row in rows:
        if row["action"] != "blocked":
            clashes.setdefault(row["to"], []).append(row)
    for to, group in clashes.items():
        if len(group) > 1:
            for row in group:
                row["action"], row["note"] = "blocked", f"another asset in this batch goes to the same path ({to})"
    return rows


def apply(items, root, confirm_licence=False, index_file=None, credits_writer=None):
    """items: [{"id", "to", "overwrite"}]. Writes the confirmed ones and returns what happened to each."""
    edits = {str(i["id"]): str(i.get("to") or "") for i in items if i.get("to")}
    rows = plan([i["id"] for i in items], root, edits)
    wanted = {str(i["id"]): bool(i.get("overwrite")) for i in items}
    base = mod_root(root)
    done, index = [], {}
    if index_file and Path(index_file).exists():
        index = json.loads(Path(index_file).read_text(encoding="utf-8"))
    for row in rows:
        result = {"id": row["id"], "title": row["title"], "to": row["to"], "result": "", "note": row["note"]}
        done.append(result)
        if row["action"] == "blocked":
            result["result"] = "refused"
            continue
        if row["needs_confirm"] and not confirm_licence:
            result["result"], result["note"] = "refused", f"{row['licence_words']}: confirm that you may use it first"
            continue
        if row["action"] == "same":
            result["result"] = "unchanged"
            continue
        if row["action"] == "overwrite" and not wanted.get(row["id"]):
            result["result"], result["note"] = "kept", "a different file is already there, and replacing it was not confirmed"
            continue
        project = projects.load(row["id"])
        if project.get("mode") == "file":
            data = projects.file_path(row["id"]).read_bytes()
        else:
            _, data, placement, _ = build_bytes(project)
        target = base / row["to"]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        result["result"] = "created" if row["action"] == "new" else "replaced"
        result["note"] = "written"
        entry = {"from": row["id"], "title": project.get("title", ""), "category": project.get("category", ""), "credit": project.get("credit"), "to": row["to"]}
        if project.get("mode") != "file":
            entry.update(row.get("placement") or {})
            index[Path(row["to"]).stem] = entry
        else:
            index["file:" + row["to"]] = entry
    if any(r["result"] in ("created", "replaced") for r in done):
        if index_file:
            Path(index_file).parent.mkdir(parents=True, exist_ok=True)
            Path(index_file).write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        if credits_writer:
            credits_writer(index)
        _log(root, done)
    return done


def _log(root, done):
    changed = [r for r in done if r["result"] in ("created", "replaced")]
    path = Path(root) / LOG
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [] if path.exists() else ["# Sent to the mod", "", "Written by Asset Studio each time assets are sent to `src/main/resources`. Newest at the bottom.", ""]
    lines.append(f"## {time.strftime('%Y-%m-%d %H:%M')}")
    lines += [f"- {r['result']}: `{r['to']}` ({r['title']})" for r in changed]
    lines.append("")
    with open(path, "a", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
